def tab(name, qkeys):
    qkeys = QL.get(name, qkeys)
    if _tab:
        emit('qlinks "%s" = %s' % (_tab["name"], ",".join(_tab["q"])))
    for k in qkeys:
        assert k == "-" or k in PARAMS, k
    assert len(qkeys) <= 16, name
    _tab.update(name=name, q=qkeys)
    emit("")
    emit("[tab %s]" % name)


def full(title, cols):          # one panel over the whole page
    return Frame(X0, Y0, X1 - X0, Y1 - Y0, title, cols)


def split(*specs):              # side by side panels: (title, cols, width share)
    tot = sum(s[2] for s in specs)
    x, out = X0, []
    for i, (t, c, share) in enumerate(specs):
        w = int((X1 - X0 - 8 * (len(specs) - 1)) * share / tot)
        out.append(Frame(x, Y0, w, Y1 - Y0, t, c))
        x += w + 8
    return out


