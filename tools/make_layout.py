class Frame:
    """A titled panel; rows of equal cells. Row kinds: knob (big), popup, toggle, enum, button, readout."""
    HT = {"knob": 158, "popup": 96, "toggle": 84, "enum": 84, "button": 76, "readout": 84}

    def __init__(self, x, y, w, h, title, cols):
        self.x, self.y, self.w, self.cols = x, y, w, cols
        self.cw = (w - 20) / cols
        self.ry = y + 40
        emit('frame x=%d y=%d w=%d h=%d title="%s"' % (x, y, w, h, q(title)))

    def row(self, items, kind="knob", span=1):
        top = self.ry
        for i, it in enumerate(items):
            if it is None:
                continue
            key, label = it
            cx = int(self.x + 10 + (i * span + span / 2) * self.cw)
            if kind == "knob":
                emit('knob cx=%d cy=%d r=40 label="%s" key=%s ns=17 vs=16 bw=%d' % (cx, top + 56, q(label), key, min(int(self.cw) - 8, 150)))
            elif kind == "popup":
                emit('popup cx=%d cy=%d w=%d h=40 label="%s" key=%s' % (cx, top + 60, min(int(self.cw * span) - 16, 240), q(label), key))
            elif kind == "toggle":
                emit('toggle cx=%d cy=%d label="%s" key=%s' % (cx, top + 40, q(label), key))
            elif kind == "button":
                emit('button cx=%d cy=%d label="%s" key=%s' % (cx, top + 38, q(label), key))
            elif kind == "enum":
                opts = ",".join(o.upper() for o in PARAMS[key]["options"])
                sw = max(56, min(int(self.cw * span / len(PARAMS[key]["options"])) - 6, 110))
                emit('enum_h cx=%d cy=%d label="%s" key=%s options="%s" sw=%d' % (cx, top + 46, q(label), key, opts, sw))
            elif kind == "readout":
                emit('readout cx=%d cy=%d w=%d h=40 label="%s" key=%s' % (cx, top + 56, int(self.cw * span) - 16, q(label), key))
        self.ry += self.HT[kind]


