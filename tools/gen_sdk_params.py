#!/usr/bin/env python3
"""params.lock + vst/params.json -> src/params_gen.h: the parameter table of the native front end (src/OsirusPlugin.cpp).

params.lock is the FROZEN VST order. Its first 300 entries are the released 0.2.11 wrapper build, read out of that build's osirus.so
(tools/released_params.py, committed as vst/released-0.2.11.tsv): the first 257 keys of vst/params.json, then the 43 hidden
"<key>__open" flags that build added, one per popup of vst/layout.conf. Saved projects and Q-Link assignments bind to these indices.
This build keeps them: index 257 is ui_open (0 = closed, k + 1 = the pick-list of the k-th popup), 258..299 are inert reserved slots.
After them come the engine keys added to vst/params.json since 0.2.11 (the BANKS page's bank pager), then the front end's own APPENDED
parameters. New parameters are only ever appended (here and in params.lock).
Favourites were engine keys already in 0.2.11 (favourite, fav_save, fav_delete): they stay in the engine.
"""
import json, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
P = json.load(open(os.path.join(ROOT, "vst", "params.json")))["params"]
LOCK = [l.strip() for l in open(os.path.join(ROOT, "params.lock")) if l.strip()]
REL = [l.rstrip("\n").split("\t") for l in open(os.path.join(ROOT, "vst", "released-0.2.11.tsv")) if l.strip()]
NREL = 257                       # engine keys in the released build
NPOP = 43                        # popups in the released build
KB_CHARS = "1234567890QWERTYUIOPASDFGHJKLZXCVBNM-"
APPENDED = [                     # (key, name, min, max, default, flags) appended after the engine keys, in this order
    ("random_patch", "RANDOM", 0, 1, 0, 1 | 512),      # kMomentary | kNoAuto: the engine's verb, a random sound from every loaded bank (BANKS page)
    # the naming keyboard for +FAV (Vavra's / Profit-5's): the typed name (a text readout), the keyboard's visibility, its keys (kLocal)
    ("fav_name", "Favourite Name", 0, 1023, 0, 2 | 4096 | 512),
    ("kb_open", "Keyboard", 0, 1, 0, 16 | 4096 | 512),
] + [("kb_" + ("dash" if c == "-" else c.lower()), "Key " + c, 0, 1, 0, 1 | 4096 | 512) for c in KB_CHARS] + [
    ("kb_space", "Key Space", 0, 1, 0, 1 | 4096 | 512), ("kb_bksp", "Key Delete", 0, 1, 0, 1 | 4096 | 512),
    ("kb_shift", "Key Shift", 0, 1, 0, 1 | 4096 | 512), ("kb_cancel", "Key Cancel", 0, 1, 0, 1 | 4096 | 512),
    ("kb_save", "Key Save", 0, 1, 0, 1 | 4096 | 512),
]
RANGE = {}
# ranges that may differ from 0.2.11: readouts, tiles and momentary keys meant nothing in a project; bank_index went 0..31 -> 0..63
# (the user-bank fix; a project restores its bank from the state chunk, not from the parameter)
RANGE_CHANGED_OK = {"bank_index"}

keys = [p["key"] for p in P]
popups = [k[:-len("__open")] for k in LOCK[NREL:NREL + NPOP]]
expect = keys[:NREL] + [k + "__open" for k in popups] + keys[NREL:] + [a[0] for a in APPENDED]
if LOCK != expect:
    for i, (a, b) in enumerate(zip(LOCK, expect)):
        if a != b:
            sys.exit("params.lock index %d is %s, the table gives %s: the order is frozen (append only)" % (i, a, b))
    sys.exit("params.lock has %d entries, the table gives %d: the order is frozen (append only)" % (len(LOCK), len(expect)))
if [r[0] for r in REL] != LOCK[:NREL + NPOP]:
    sys.exit("params.lock's first %d entries are not the released 0.2.11 table (vst/released-0.2.11.tsv)" % (NREL + NPOP))
if not all(k in keys for k in popups):
    sys.exit("a popup in params.lock is not an engine key")
idx = {k: i for i, k in enumerate(keys)}

FL = dict(kMomentary=1, kText=2, kChoice=8, kUi=16, kReserved=32, kStep=128, kTile=256, kNoAuto=512, kPolled=1024,
          kRefresh=2048, kLocal=4096)
out = ["/* generated by tools/gen_sdk_params.py from params.lock + vst/params.json: do not edit. One row per parameter, frozen VST order. */",
       "#pragma once",
       "enum { %s };" % ", ".join("%s = %d" % kv for kv in FL.items()),
       "struct PSpec { const char *key, *name; float min, max, def; int flags; const char *const *choices; int nchoices; int stepTarget; float stepDelta; };",
       ""]
rows = []
vst_index = {k: LOCK.index(k) for k in keys}
idx = {k: keys.index(k) for k in keys}   # the first index of a key


def F(v):
    t = "%g" % v
    return t + ("f" if ("." in t or "e" in t) else ".0f")


def row(key, name, lo, hi, d, fl, ch="nullptr", n=0, st=-1, sd=0.0):
    rows.append("    {%s, %s, %s, %s, %s, %d, %s, %d, %d, %s}," % (json.dumps(key), json.dumps(name), F(lo), F(hi), F(d), fl, ch, n, st, F(sd)))


def engine_row(i, p):
    k = p["key"]
    fl, ch, n, st, sd = 0, "nullptr", 0, -1, 0.0
    if p.get("refresh_display"):
        fl |= FL["kRefresh"]
    if "options" in p:
        opts = p["options"]
        fl |= FL["kChoice"] | FL["kPolled"]
        out.append("static const char *const ch_%d[] = {%s};" % (i, ", ".join(json.dumps(o) for o in opts)))
        ch, n = "ch_%d" % i, len(opts)
        d = opts.index(p["default"]) if isinstance(p["default"], str) else p["default"]
        lo, hi = 0, len(opts) - 1
    else:
        lo, hi, d = p.get("min", 0), p.get("max", 1), p.get("default", 0)
        lo, hi = RANGE.get(k, (lo, hi))
        if k.startswith("bank_slot_") or k.startswith("patch_slot_"):
            fl |= FL["kMomentary"] | FL["kText"] | FL["kTile"] | FL["kNoAuto"]      # list tiles: tap = pick, lit = "<key>_on"
            lo, hi = 0, 1
        elif p.get("momentary"):
            fl |= FL["kMomentary"] | FL["kNoAuto"]
            lo, hi = 0, 1
            if p.get("step_of"):
                fl |= FL["kStep"]
                st, sd = vst_index[p["step_of"]], p.get("step_delta", 1)
        elif p.get("display") == "string":
            fl |= FL["kText"] | FL["kNoAuto"]                                        # readouts: the value is a change counter
            lo, hi, d = 0, 1023, 0
        else:
            fl |= FL["kPolled"]
    if k in ("bank_index", "preset", "favourite"):
        fl |= FL["kNoAuto"]
    if i < NREL and not fl & (FL["kText"] | FL["kMomentary"] | FL["kTile"]) and k not in RANGE_CHANGED_OK:
        r = REL[i]       # key, min, max, normalised default, option count
        rlo, rhi, rdef, ropts = float(r[1]), float(r[2]), float(r[3]), int(r[4])
        if ropts > 1:
            rlo, rhi = 0, ropts - 1
        ndef = (d - lo) / (hi - lo) if hi > lo else 0
        if (rlo, rhi) != (lo, hi) or abs(ndef - rdef) > 1e-4:
            sys.exit("%s: range %g..%g default %g, released 0.2.11 had %g..%g default %g (normalised)" % (k, lo, hi, ndef, rlo, rhi, rdef))
    row(k, p["name"], lo, hi, d, fl, ch, n, st, sd)


seen = set()
for i, p in enumerate(P[:NREL]):
    if p["key"] in seen:   # 0.2.11's table had rom_bc twice (250, 251): the SDK restores by id, so the second is an inert slot of its own
        row(p["key"] + "_2", p["name"] + " (2)", 0, 1, 0, FL["kReserved"] | FL["kNoAuto"])
        continue
    seen.add(p["key"])
    engine_row(i, p)
row("ui_open", "Pick List", 0, len(popups), 0, FL["kUi"] | FL["kNoAuto"])
for j in range(1, len(popups)):
    row("rsv_%d" % (NREL + j), "Reserved %d" % j, 0, 1, 0, FL["kReserved"] | FL["kNoAuto"])
for i, p in enumerate(P[NREL:], NREL):
    engine_row(i, p)
for a in APPENDED:
    row(*a)

out += ["static const char *const g_popups[] = {%s};" % ", ".join(json.dumps(k) for k in popups)]
out += ["", "static const PSpec g_pspecs[] = {"] + rows + ["};",
        "static const int kNumParams = %d;" % len(LOCK),
        "static const int kNumReleasedKeys = %d;   // 0 .. this - 1 are engine keys" % NREL,
        "static const int kUiParam = %d;            // ui_open: 0 closed, k + 1 = pick-list of g_popups[k]" % NREL,
        "static const int kNumPopups = %d;" % len(popups),
        "static const int kFirstNewEngine = %d, kNumNewEngine = %d;   // engine keys appended since 0.2.11" % (NREL + NPOP, len(keys) - NREL),
        "static const int kFavourite = %d, kFavSave = %d, kFavDelete = %d, kFavSlots = 64;" % (idx["favourite"], idx["fav_save"], idx["fav_delete"]),
        "static const int kRandom = %d;" % LOCK.index("random_patch"),
        "static const int kRomBc = %d;             // B/C ROM: engine-owned (the loaded ROM)" % idx["rom_bc"],
        "static const int kFavName = %d, kKbOpen = %d, kKbFirst = %d, kKbCount = %d;" % (LOCK.index("fav_name"), LOCK.index("kb_open"),
                                                                                      LOCK.index("kb_1"), len(KB_CHARS) + 5),
        "static const char kKbChars[] = %s;   // the character keys from kKbFirst, then space, delete, shift, cancel, save" % json.dumps(KB_CHARS),
        "static const int kFavNameMax = 20;",
        "static const int kFirstAppended = %d;     // the front end's own parameters" % LOCK.index("random_patch"), ""]
open(os.path.join(ROOT, "src", "params_gen.h"), "w").write("\n".join(out))
print("src/params_gen.h: %d params (%d released keys, ui_open, %d reserved, %d new engine keys, %d appended)" % (
    len(LOCK), NREL, len(popups) - 1, len(keys) - NREL, len(APPENDED)))
